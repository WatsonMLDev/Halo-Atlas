#!/usr/bin/env python3
"""Extract the PebbleOS syscall jump table from SDK libpebble.a and emit C stubs."""

from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import subprocess
import sys

SYMBOL_RE = re.compile(r"^[0-9a-fA-F]+\s+<([^>]+)>:\s*$")
MOV_R1_RE = re.compile(r"\bmov(?:\.w|w)?\s+r1,\s*#(0x[0-9a-fA-F]+|\d+)\b")
SKIP_SYMBOLS = {"jump_to_pbl_function", "pbl_table_addr"}


def find_objdump() -> str:
    for tool in ("llvm-objdump", "arm-none-eabi-objdump", "objdump"):
        found = shutil.which(tool)
        if found:
            return found
    raise RuntimeError("No objdump binary found (tried llvm-objdump, arm-none-eabi-objdump, objdump)")


def parse_libpebble(lib_path: pathlib.Path) -> dict[int, str]:
    if not lib_path.is_file():
        raise FileNotFoundError(f"libpebble.a not found: {lib_path}")

    objdump = find_objdump()
    proc = subprocess.run(
        [objdump, "-d", str(lib_path)],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"{objdump} failed on {lib_path}: {proc.stderr.strip()}")

    slots: dict[int, str] = {}
    current_sym: str | None = None
    for line in proc.stdout.splitlines():
        sym_match = SYMBOL_RE.match(line)
        if sym_match:
            sym = sym_match.group(1)
            current_sym = None if sym in SKIP_SYMBOLS else sym
            continue

        if current_sym is None:
            continue

        mov_match = MOV_R1_RE.search(line)
        if mov_match:
            byte_offset = int(mov_match.group(1), 0)
            if byte_offset % 4 != 0:
                raise ValueError(
                    f"Symbol {current_sym} has non-word-aligned jump offset {byte_offset:#x}"
                )
            slot = byte_offset // 4
            if slot in slots and slots[slot] != current_sym:
                raise ValueError(
                    f"Duplicate syscall slot {slot}: {slots[slot]} vs {current_sym}"
                )
            slots[slot] = current_sym
            current_sym = None

    if not slots:
        raise ValueError(f"No PebbleOS syscall shims found in {lib_path}")
    return slots


def sanitize_macro(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name).upper()


def render_header(slots: dict[int, str], total_slots: int) -> str:
    lines = [
        "/* AUTO-GENERATED by tools/gen_syscall_table.py — DO NOT EDIT. */",
        "#ifndef PEBBLE_SYSCALL_TABLE_GEN_H",
        "#define PEBBLE_SYSCALL_TABLE_GEN_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define PEBBLE_SYSCALL_TABLE_SLOTS {total_slots}",
        f"#define PEBBLE_SYSCALL_SYMBOL_COUNT {len(slots)}",
        "",
    ]
    for slot in sorted(slots):
        macro = sanitize_macro(slots[slot])
        lines.append(f"#define PEBBLE_SYS_{macro} {slot}")

    lines.extend(
        [
            "",
            "extern const char *const pebble_syscall_names[PEBBLE_SYSCALL_TABLE_SLOTS];",
            "",
            "/* Populates table_out[0..PEBBLE_SYSCALL_TABLE_SLOTS-1] with safe default stubs. */",
            "void pebble_syscall_table_init_defaults(void **table_out);",
            "",
            "/* Returns the human-readable symbol name (or reserved placeholder) for a slot. */",
            "const char *pebble_syscall_name(uint32_t slot);",
            "",
            "/* Implemented by the core runtime: logs unimplemented calls and returns 0. */",
            "uint64_t pebble_syscall_default_stub(",
            "    uint32_t slot, uintptr_t r0, uintptr_t r1, uintptr_t r2, uintptr_t r3);",
            "",
            "#endif /* PEBBLE_SYSCALL_TABLE_GEN_H */",
            "",
        ]
    )
    return "\n".join(lines)


def render_source(slots: dict[int, str], total_slots: int) -> str:
    lines = [
        "/* AUTO-GENERATED by tools/gen_syscall_table.py — DO NOT EDIT. */",
        '#include "pebble_syscall_table_gen.h"',
        "",
        "const char *const pebble_syscall_names[PEBBLE_SYSCALL_TABLE_SLOTS] = {",
    ]
    for slot in range(total_slots):
        name = slots.get(slot, f"<reserved_slot_{slot}>")
        lines.append(f'    [{slot}] = "{name}",')
    lines.extend(["};", ""])

    for slot in range(total_slots):
        lines.append(
            f"static uint64_t pebble_stub_slot_{slot}("
            "uintptr_t r0, uintptr_t r1, uintptr_t r2, uintptr_t r3) {"
        )
        lines.append(
            f"    return pebble_syscall_default_stub({slot}u, r0, r1, r2, r3);"
        )
        lines.append("}")

    lines.extend(
        [
            "",
            "static void *const pebble_default_stubs[PEBBLE_SYSCALL_TABLE_SLOTS] = {",
        ]
    )
    for slot in range(total_slots):
        lines.append(f"    [{slot}] = pebble_stub_slot_{slot},")
    lines.extend(
        [
            "};",
            "",
            "void pebble_syscall_table_init_defaults(void **table_out) {",
            "    for (uint32_t i = 0; i < PEBBLE_SYSCALL_TABLE_SLOTS; ++i) {",
            "        table_out[i] = pebble_default_stubs[i];",
            "    }",
            "}",
            "",
            "const char *pebble_syscall_name(uint32_t slot) {",
            "    if (slot >= PEBBLE_SYSCALL_TABLE_SLOTS) {",
            '        return "<out_of_range>";',
            "    }",
            "    return pebble_syscall_names[slot];",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate PebbleOS syscall jump table stubs from libpebble.a"
    )
    parser.add_argument("--lib", required=True, type=pathlib.Path, help="Path to SDK libpebble.a")
    parser.add_argument(
        "--out-dir", required=True, type=pathlib.Path, help="Output directory for generated C files"
    )
    args = parser.parse_args(argv)

    try:
        slots = parse_libpebble(args.lib)
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    total_slots = max(slots) + 1
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "pebble_syscall_table_gen.h").write_text(
        render_header(slots, total_slots), encoding="utf-8"
    )
    (args.out_dir / "pebble_syscall_table_gen.c").write_text(
        render_source(slots, total_slots), encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
