#!/usr/bin/env python3
"""Generate a C header embedding an unpacked .pbw binary and resource pack for Zephyr QEMU."""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parent.parent


def _load_unpack_pbw():
    pbw_path = REPO_ROOT / "python" / "halo_atlas" / "pbw.py"
    spec = importlib.util.spec_from_file_location("halo_atlas_pbw", pbw_path)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod.unpack_pbw


unpack_pbw = _load_unpack_pbw()


def _format_c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Embed unpacked .pbw binary + resources into a C header")
    parser.add_argument("--pbw", required=True, type=Path, help="Input .pbw archive")
    parser.add_argument("--platform", default=None, help="Optional Pebble platform override")
    parser.add_argument("--out", required=True, type=Path, help="Output C header path")
    args = parser.parse_args()

    unpacked = unpack_pbw(args.pbw, preferred_platform=args.platform)
    platform_enum = {
        "chalk": "PEBBLE_PLATFORM_CHALK",
        "gabbro": "PEBBLE_PLATFORM_GABBRO",
        "basalt": "PEBBLE_PLATFORM_BASALT",
        "aplite": "PEBBLE_PLATFORM_APLITE",
    }[unpacked.platform]

    res_bytes = unpacked.resources_pbpack or b""
    content = "\n".join(
        [
            "/* Auto-generated by tools/gen_embedded_pbw.py — do not edit. */",
            "#ifndef PEBBLE_EMBEDDED_PBW_H",
            "#define PEBBLE_EMBEDDED_PBW_H",
            "",
            "#include <stddef.h>",
            "#include <stdint.h>",
            '#include "pebble_compat.h"',
            "",
            f"#define PEBBLE_EMBEDDED_PLATFORM {platform_enum}",
            f'#define PEBBLE_EMBEDDED_PLATFORM_NAME "{unpacked.platform}"',
            "",
            _format_c_array("g_embedded_pbw_bin", unpacked.app_bin),
            f"static const size_t g_embedded_pbw_bin_len = {len(unpacked.app_bin)}u;",
            "",
            (
                _format_c_array("g_embedded_pbw_res", res_bytes)
                if res_bytes
                else "static const uint8_t g_embedded_pbw_res[1] = { 0x00 };"
            ),
            f"static const size_t g_embedded_pbw_res_len = {len(res_bytes)}u;",
            "",
            "#endif /* PEBBLE_EMBEDDED_PBW_H */",
            "",
        ]
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
